#!/usr/bin/env python3
"""Generates src/output/nonprintable.rs: the codepoint ranges where Python's `str.isprintable()`
is false (Unicode categories Cc, Cf, Cs, Co, Cn, Zl, Zp and Zs except the ASCII space), which
`repr()` of a `str` escapes. Run it with the Python version snow runs on; the version goes in
the header of the table, so a refresh is a diff of this file.

Usage: scripts/gen_nonprintable.py > src/output/nonprintable.rs
"""
import sys
import unicodedata

ranges = []
start = None
for cp in range(0x110000 + 1):
    bad = cp < 0x110000 and not chr(cp).isprintable()
    if bad and start is None:
        start = cp
    elif not bad and start is not None:
        ranges.append((start, cp - 1))
        start = None

v = sys.version_info
print(f"//! Generated by scripts/gen_nonprintable.py. Do not edit by hand.")
print(f"//! Python {v.major}.{v.minor}.{v.micro}, Unicode {unicodedata.unidata_version}.")
print()
print("/// Inclusive codepoint ranges where Python's `str.isprintable()` is false.")
print("pub(crate) const NON_PRINTABLE: &[(u32, u32)] = &[")
for lo, hi in ranges:
    print(f"    (0x{lo:04x}, 0x{hi:04x}),")
print("];")
